//! Writes the IDs of `resources/ids.h` as Rust into `OUT_DIR` for `core::ids`,
//! compiles `resources/gozler-ui.rc` into the executable on Windows, and, with
//! the `pseudo-language` feature, writes the pseudo-language catalogue
//! `qps-ploc.json` into `OUT_DIR` for `core::text` to embed.
//!
//! The version reaches the .rc file through `version.rh` in `OUT_DIR`, so the
//! version information has one source, the workspace version.

fn main() {
    println!("cargo::rerun-if-changed=resources");
    ids::write();
    if std::env::var("CARGO_CFG_TARGET_OS").is_ok_and(|os| os == "windows") {
        let var = |name: &str| std::env::var(name).expect("cargo sets the version and OUT_DIR");
        let header = format!(
            "#define GOZLER_VERSION \"{}\"\n#define GOZLER_VERSION_NUMBERS {},{},{},0\n",
            var("CARGO_PKG_VERSION"),
            var("CARGO_PKG_VERSION_MAJOR"),
            var("CARGO_PKG_VERSION_MINOR"),
            var("CARGO_PKG_VERSION_PATCH"),
        );
        // embed-resource passes OUT_DIR to rc.exe as an include folder.
        std::fs::write(
            std::path::Path::new(&var("OUT_DIR")).join("version.rh"),
            header,
        )
        .expect("OUT_DIR is writable");
        embed_resource::compile("resources/gozler-ui.rc", embed_resource::NONE)
            .manifest_required()
            .expect("rc.exe compiles resources/gozler-ui.rc");
    }
    #[cfg(feature = "pseudo-language")]
    pseudo::write();
}

/// `ids.rs` in `OUT_DIR`, the enums of `resources/ids.h` that `core::ids`
/// includes, after the checks that rc.exe and rustc do not make.
mod ids {
    use std::collections::HashMap;
    use std::fmt::Write;

    /// The IDs whose names start with `prefix`, which become the enum
    /// `name`.
    struct Kind {
        prefix: &'static str,
        name: &'static str,
        ids: Vec<(String, u16)>,
    }

    pub(super) fn write() {
        let header = std::fs::read_to_string("resources/ids.h").expect("ids.h is readable");
        let script =
            std::fs::read_to_string("resources/gozler-ui.rc").expect("the .rc is readable");
        let mut kinds = [
            ("IDI_", "IconId"),
            ("IDD_", "DialogId"),
            ("IDC_", "ControlId"),
        ]
        .map(|(prefix, name)| Kind {
            prefix,
            name,
            ids: Vec::new(),
        });
        let mut controls = HashMap::new();
        for line in header.lines() {
            let mut words = line.split_whitespace();
            let (Some("#define"), Some(name), Some(value)) =
                (words.next(), words.next(), words.next())
            else {
                continue;
            };
            let value: u16 = value
                .parse()
                .unwrap_or_else(|_| panic!("{name} is not a number"));
            let kind = kinds
                .iter_mut()
                .find(|kind| name.starts_with(kind.prefix))
                .unwrap_or_else(|| panic!("{name} starts with none of IDI_, IDD_ and IDC_"));
            match kind.prefix {
                // A dialog sends IDOK and IDCANCEL for Enter and Esc, so a
                // control with either ID would act as one of them.
                "IDC_" if value == 1 || value == 2 => {
                    panic!("{name} is {value}, the ID of IDOK or IDCANCEL")
                }
                "IDC_" => {
                    if let Some(other) = controls.insert(value, name.to_owned()) {
                        panic!("{name} and {other} are both {value}");
                    }
                }
                "IDD_" if !script.contains(&format!("{name} DIALOGEX")) => {
                    panic!("gozler-ui.rc has no {name} DIALOGEX")
                }
                _ => {}
            }
            kind.ids.push((name[kind.prefix.len()..].to_owned(), value));
        }
        let mut code = String::from("// Generated by build.rs from resources/ids.h.\n");
        for Kind {
            name: kind, ids, ..
        } in &kinds
        {
            let variants: Vec<String> = ids.iter().map(|(name, _)| camel_case(name)).collect();
            // resources/ids.h also names IDs that only the .rc file uses.
            let _ = write!(
                code,
                "\n#[allow(dead_code)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n#[repr(u16)]\npub(crate) enum {kind} {{\n"
            );
            for (variant, (_, value)) in variants.iter().zip(ids) {
                let _ = writeln!(code, "    {variant} = {value},");
            }
            let _ = write!(code, "}}\n\nimpl {kind} {{\n");
            // Tests check every dialog; no test needs the other kinds' lists.
            let _ = writeln!(
                code,
                "    #[cfg(test)]\n    #[allow(dead_code)]\n    pub(crate) const ALL: [{kind}; {}] = [{}];\n",
                variants.len(),
                variants
                    .iter()
                    .map(|v| format!("{kind}::{v}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let _ = write!(
                code,
                "    pub(crate) fn id(self) -> u16 {{\n        self as u16\n    }}\n}}\n"
            );
        }
        let out = std::path::Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
            .join("ids.rs");
        std::fs::write(out, code).expect("OUT_DIR is writable");
    }

    /// `SEARCH_SYNTAX_TEXT` as `SearchSyntaxText`.
    fn camel_case(name: &str) -> String {
        name.split('_')
            .map(|word| {
                let mut chars = word.chars();
                chars.next().map_or(String::new(), |first| {
                    first.to_string() + &chars.as_str().to_lowercase()
                })
            })
            .collect()
    }
}

/// The pseudo-language: Windows' own long-text pseudo-locale tag, with every
/// message lengthened and accented so that clipping and untranslated text
/// show in a screenshot (docs/plans/ui-design.md: Text and languages).
#[cfg(feature = "pseudo-language")]
mod pseudo {
    use serde_json::Value;

    pub(super) fn write() {
        let english = std::fs::read_to_string("resources/en.json").expect("en.json is readable");
        let mut catalogue: Value = serde_json::from_str(&english).expect("en.json parses");
        let Value::Object(groups) = &mut catalogue else {
            panic!("en.json holds one level of objects")
        };
        for group in groups.values_mut() {
            let Value::Object(messages) = group else {
                panic!("en.json holds one level of objects")
            };
            for message in messages.values_mut() {
                if let Value::String(text) = message {
                    *text = lengthen(text);
                }
            }
        }
        let out = std::path::Path::new(&std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
            .join("qps-ploc.json");
        std::fs::write(
            out,
            serde_json::to_string(&catalogue).expect("a Value serializes"),
        )
        .expect("OUT_DIR is writable");
    }

    /// A message of up to 12 characters becomes twice as long, a longer one
    /// half as long again. Placeholders and the access key's letter stay as
    /// they are, so formatting and the access keys work as in English.
    fn lengthen(text: &str) -> String {
        let mut out = String::from("[");
        let mut visible: usize = 0;
        let mut chars = text.chars().peekable();
        while let Some(c) = chars.next() {
            match c {
                '{' => {
                    out.push(c);
                    for c in chars.by_ref() {
                        out.push(c);
                        if c == '}' {
                            break;
                        }
                    }
                    visible += 3;
                }
                '&' => {
                    out.push(c);
                    if let Some(key) = chars.next() {
                        out.push(key);
                    }
                    visible += 1;
                }
                _ => {
                    out.push(accented(c));
                    visible += 1;
                }
            }
        }
        let target = if visible <= 12 {
            visible * 2
        } else {
            (visible * 3).div_ceil(2)
        };
        for _ in visible + 2..target {
            out.push('·');
        }
        out.push(']');
        out
    }

    fn accented(c: char) -> char {
        const PLAIN: &str = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
        const ACCENTED: &str = "áƀçďéƒĝĥíĵķĺɱñóþǫŕšŧúṽŵẋýžÁƁÇĎÉƑĜĤÍĴĶĹṀÑÓÞǪŔŠŦÚṼŴẊÝŽ";
        PLAIN
            .chars()
            .position(|p| p == c)
            .and_then(|i| ACCENTED.chars().nth(i))
            .unwrap_or(c)
    }
}
